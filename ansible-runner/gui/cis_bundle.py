"""Standalone CIS bundles: one .tar.gz per Linux CIS profile, to run on a machine
without the ansible-runner (copied over, offline once Ansible is installed).

    cis-<os>/
      README.txt
      install-ansible.sh      ansible-core >= 2.16 (distro package, else a venv in ./venv)
      run-cis.sh              ./run-cis.sh audit|apply [1-server|2-server|1-workstation|2-workstation]
      site.yml, ansible.cfg   localhost play - same safety settings as playbooks/cis_hardening_linux.yml
      roles/<ROLE>/           the ansible-lockdown role the GUI uses
      collections/            ansible.posix, community.general, community.crypto
      audit/goss              audit binary (linux amd64) - no download needed
      audit/<ROLE>-Audit/     the benchmark's audit rules - no git clone needed
      reports/                filled by run-cis.sh (log + audit results per run)

Built on demand by /api/cis/bundle/<os> and cached in gui/data/cis-bundles.
"""
import io
import json
import pathlib
import re
import shutil
import tarfile
import tempfile
import time
import urllib.request

import yaml

ROLES_DIR = pathlib.Path("/usr/share/ansible/roles")
COLLECTIONS_DIR = pathlib.Path("/usr/share/ansible/collections/ansible_collections")
COLLECTIONS = ("ansible/posix", "community/general", "community/crypto")
MAX_AGE = 7 * 86400   # rebuild a cached bundle after a week (or when the role changes)


def _role_meta(role_dir: pathlib.Path) -> dict:
    """benchmark, benchmark_version and the goss release the role's audit expects."""
    text = "\n".join(p.read_text(errors="ignore") for p in sorted((role_dir / "defaults").rglob("*.yml")))
    get = lambda key: (re.search(rf"^{key}:\s*['\"]?([^'\"\n]+)", text, re.M) or [None, None])[1]
    release = re.search(r"^audit_bin_version:\s*\n(?:\s+.*\n)*?\s+release:\s*['\"]?([^'\"\n]+)", text, re.M)
    return {"benchmark": get("benchmark"), "benchmark_version": get("benchmark_version"),
            "goss_release": release.group(1).strip() if release else "v0.5.0"}


def _download(url: str, dest: pathlib.Path) -> pathlib.Path:
    if not dest.exists():
        dest.parent.mkdir(parents=True, exist_ok=True)
        tmp = dest.with_suffix(dest.suffix + ".part")
        with urllib.request.urlopen(url, timeout=300) as r, open(tmp, "wb") as f:
            shutil.copyfileobj(r, f)
        tmp.rename(dest)
    return dest


def _site_yml(profile: dict, playbook_path: pathlib.Path, meta: dict) -> str:
    play = yaml.safe_load(playbook_path.read_text())[0]
    vars_ = {k: v for k, v in play["vars"].items() if k != "cis_role"}
    bench = meta["benchmark"]
    vars_.update({
        "cis_role": profile["role"],
        # Audit fully offline: goss and the audit rules come with the bundle
        "get_audit_binary_method": "copy",
        "audit_bin_copy_location": "{{ playbook_dir }}/audit/goss",
        "audit_content": "copy",
        "audit_conf_source": "{{ playbook_dir }}/audit/" + f"{bench}-Audit",
        "audit_conf_dest": "/opt",
        "fetch_audit_output": False,
    })
    keep = {"Gather facts (the roles need them)", "Check for container / VM runtimes that need IP forwarding",
            "Keep IP forwarding on where a runtime needs it", "Report the runtime check"}
    pre = [t for t in play.get("pre_tasks", []) if t.get("name") in keep]
    doc = [{"name": f"CIS {profile['label']} ({profile['role']}) - standalone, on this machine",
            "hosts": "localhost", "connection": "local", "become": True, "gather_facts": False,
            "vars": vars_, "pre_tasks": pre, "tasks": play["tasks"]}]
    head = (f"# Standalone CIS run for {profile['label']} - generated by the ansible-runner GUI from\n"
            "# playbooks/cis_hardening_linux.yml (same safety settings). Use ./run-cis.sh, not this file directly.\n")
    return head + yaml.safe_dump(doc, sort_keys=False, width=120)


INSTALL_SH = r'''#!/bin/bash
# Installs ansible-core >= 2.16 (what the CIS roles need) - needs package/PyPI access ONCE.
# Uses the distro package when it is new enough, otherwise a private venv in ./venv.
set -euo pipefail
cd "$(dirname "$0")"
need="2.16"
ver_ok() { [ "$(printf '%s\n%s\n' "$need" "$1" | sort -V | head -1)" = "$need" ]; }
have() { ansible --version 2>/dev/null | head -1 | grep -oE '[0-9]+\.[0-9]+(\.[0-9]+)?' | head -1; }
SUDO=""; [ "$(id -u)" -ne 0 ] && SUDO="sudo"
. /etc/os-release
echo "OS: $PRETTY_NAME"
if [ -x ./venv/bin/ansible-playbook ]; then echo "ansible already in ./venv: $(./venv/bin/ansible --version | head -1)"; exit 0; fi
if v=$(have) && [ -n "$v" ] && ver_ok "$v"; then echo "ansible-core $v already installed"; exit 0; fi
case "$ID ${ID_LIKE:-}" in
  *rhel*|*fedora*|*centos*|*rocky*|*almalinux*)
    $SUDO dnf -y install ansible-core python3 tar >/dev/null 2>&1 || true ;;
  *debian*|*ubuntu*)
    $SUDO apt-get update -qq && $SUDO apt-get install -y -qq ansible-core python3 python3-venv >/dev/null 2>&1 || true ;;
esac
if v=$(have) && [ -n "$v" ] && ver_ok "$v"; then echo "installed ansible-core $v (distro package)"; exit 0; fi
echo "distro ansible-core is missing or older than $need - installing a private copy in ./venv"
PY=""
for p in python3.13 python3.12 python3.11 python3.10 python3; do
  command -v $p >/dev/null && $p -c 'import sys; sys.exit(0 if sys.version_info >= (3,10) else 1)' && { PY=$p; break; }
done
if [ -z "$PY" ]; then
  case "$ID ${ID_LIKE:-}" in
    *rhel*|*fedora*|*centos*|*rocky*|*almalinux*) $SUDO dnf -y install python3.12 python3.12-pip && PY=python3.12 ;;
    *) echo "ERROR: ansible-core $need needs Python 3.10+ (this system has $(python3 --version 2>&1))."; exit 1 ;;
  esac
fi
$PY -m venv ./venv
./venv/bin/pip install -q --upgrade pip
./venv/bin/pip install -q "ansible-core>=2.16,<2.20"
echo "installed $(./venv/bin/ansible --version | head -1) in ./venv"
'''

RUN_SH = r'''#!/bin/bash
# CIS __LABEL__ (__ROLE__) on THIS machine.
#   ./run-cis.sh audit [level]    report only - nothing is changed
#   ./run-cis.sh apply [level]    REAL hardening (asks to confirm; -y to skip), with an audit before and after
# level: 1-server (default) | 2-server | 1-workstation | 2-workstation
# Results: ./reports/<date>-<mode>/  (ansible.log + the audit files)
set -euo pipefail
cd "$(dirname "$0")"
MODE="${1:-}"; LEVEL="1-server"; YES=""
case "$MODE" in audit|apply) shift ;; *) sed -n '2,7p' "$0"; exit 2 ;; esac
for a in "$@"; do case "$a" in -y) YES=-y ;; *) LEVEL="$a" ;; esac; done
case "$LEVEL" in
  1-server) TAGS="level1-server"; L2=false ;;
  2-server) TAGS="level1-server,level2-server"; L2=true ;;
  1-workstation) TAGS="level1-workstation"; L2=false ;;
  2-workstation) TAGS="level1-workstation,level2-workstation"; L2=true ;;
  *) echo "unknown level '$LEVEL' (1-server, 2-server, 1-workstation, 2-workstation)"; exit 2 ;;
esac
if [ -x ./venv/bin/ansible-playbook ]; then AP=./venv/bin/ansible-playbook; else AP=$(command -v ansible-playbook || true); fi
[ -n "$AP" ] || { echo "ansible not installed - run ./install-ansible.sh first"; exit 1; }
. /etc/os-release
echo "This bundle: __LABEL__ (__ROLE__).  This machine: $PRETTY_NAME"
SUDO=""; [ "$(id -u)" -ne 0 ] && SUDO="sudo -E"
if [ "$MODE" = apply ] && [ "$YES" != "-y" ]; then
  echo; echo "APPLY changes real security settings (services, sysctl, PAM/passwords, sshd, permissions...) at $LEVEL."
  echo "Run 'audit' first. SSH from other accounts, IP forwarding (Docker) and the firewall section are protected"
  echo "the same way as the ansible-runner GUI does it."
  read -r -p "Type APPLY to continue: " ok; [ "$ok" = "APPLY" ] || { echo "cancelled"; exit 1; }
fi
OUT="reports/$(date +%Y%m%d-%H%M%S)-$MODE-$LEVEL"; mkdir -p "$OUT"; touch "$OUT/.start"
EV="{\"__PREFIX___level_1\": true, \"__PREFIX___level_2\": $L2, \"setup_audit\": true, \"run_audit\": true"
[ "$MODE" = audit ] && EV="$EV, \"audit_only\": true"
EV="$EV}"
T="$TAGS"; [ "$MODE" = audit ] && T="$TAGS,run_audit"
echo "running: $MODE $LEVEL (tags $T) - log in $OUT/ansible.log"
set +e
$SUDO env ANSIBLE_CONFIG=./ansible.cfg ANSIBLE_LOG_PATH="$OUT/ansible.log" "$AP" site.yml --tags "$T" -e "$EV"
rc=$?
set -e
# audit output written by THIS run (the role leaves older scans in /opt too)
$SUDO sh -c "find /opt -maxdepth 3 -type f -newer '$OUT/.start' \( -name '*__ROLE__*.json' -o -path '*audit_summaries*' \) -exec cp {} '$OUT/' \; ; chown -R $(id -u):$(id -g) '$OUT'" || true
rm -f "$OUT/.start"
echo; sed 's/\x1b\[[0-9;]*m//g' "$OUT/ansible.log" | grep -aoE '(The audit results are|Pre Audit Results|Post Audit Results)[^"]*' | tail -3 || true
echo "results in $OUT"; exit $rc
'''

README = """CIS {label} - standalone bundle ({role}, benchmark {bench} {bver})
Generated by the ansible-runner GUI on {built}.

1. Copy this folder to the machine (e.g. scp the .tar.gz, then: tar xzf ...).
2. ./install-ansible.sh        once - needs package/PyPI access ONCE (or install
                               ansible-core >= 2.16 yourself). Everything else is in the bundle.
3. ./run-cis.sh audit          report only, nothing changed. Level: add 1-server (default),
                               2-server, 1-workstation or 2-workstation.
4. ./run-cis.sh apply 1-server REAL hardening (asks you to type APPLY; add -y to skip).
                               Audits before and after; reboot afterwards.
Reports: ./reports/<date>-<mode>-<level>/  (ansible.log, audit summaries and results)

Same safety settings as the ansible-runner: "high disruption" controls off, IPv6 not
required (disabled), no sshd AllowUsers (other accounts keep SSH), custom authselect
profile name, firewall section (4) off, IP forwarding kept on if Docker/Podman/libvirt
is installed. Change them at the top of site.yml (vars) if you need to.
Only for {label}: the role stops on any other OS version.
"""


def build(key: str, profile: dict, playbook_path: pathlib.Path, out_dir: pathlib.Path) -> pathlib.Path:
    role_dir = ROLES_DIR / profile["role"]
    if not role_dir.is_dir():
        raise FileNotFoundError(f"role {profile['role']} is not installed in the runner")
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / f"cis-{key}.tar.gz"
    newest_src = max(p.stat().st_mtime for p in [role_dir, playbook_path, pathlib.Path(__file__)])
    if out.exists() and out.stat().st_mtime > newest_src and time.time() - out.stat().st_mtime < MAX_AGE:
        return out
    meta = _role_meta(role_dir)
    bench, bver = meta["benchmark"], meta["benchmark_version"]
    cache = out_dir / "cache"
    goss = _download(f"https://github.com/krameff/goss/releases/download/{meta['goss_release']}/goss-linux-amd64",
                     cache / f"goss-{meta['goss_release']}-linux-amd64")
    audit_tgz = _download(f"https://codeload.github.com/ansible-lockdown/{bench}-Audit/tar.gz/refs/heads/benchmark_{bver}",
                          cache / f"{bench}-Audit-benchmark_{bver}.tar.gz")
    top = f"cis-{key}"
    with tempfile.TemporaryDirectory() as tmp:
        root = pathlib.Path(tmp) / top
        (root / "audit").mkdir(parents=True)
        (root / "reports").mkdir()
        shutil.copytree(role_dir, root / "roles" / profile["role"], symlinks=True)
        for c in COLLECTIONS:
            shutil.copytree(COLLECTIONS_DIR / c, root / "collections" / "ansible_collections" / c, symlinks=True,
                            ignore=shutil.ignore_patterns("tests", "docs", "*.pyc", "__pycache__", "changelogs"))
        shutil.copy2(goss, root / "audit" / "goss")
        (root / "audit" / "goss").chmod(0o755)
        with tarfile.open(audit_tgz) as t:
            t.extractall(root / "audit", filter="data")
        extracted = next(p for p in (root / "audit").iterdir() if p.is_dir())
        extracted.rename(root / "audit" / f"{bench}-Audit")
        (root / "site.yml").write_text(_site_yml(profile, playbook_path, meta))
        (root / "ansible.cfg").write_text(
            "[defaults]\ninventory = localhost,\nroles_path = ./roles\ncollections_path = ./collections\n"
            "retry_files_enabled = False\nlocalhost_warning = False\ninterpreter_python = auto_silent\n"
            "stdout_callback = default\ncallback_result_format = yaml\n")
        (root / "install-ansible.sh").write_text(INSTALL_SH)
        (root / "run-cis.sh").write_text(RUN_SH.replace("__LABEL__", profile["label"]).replace("__ROLE__", profile["role"])
                                         .replace("__PREFIX__", profile["var_prefix"]))
        for s in ("install-ansible.sh", "run-cis.sh"):
            (root / s).chmod(0o755)
        (root / "README.txt").write_text(README.format(label=profile["label"], role=profile["role"], bench=bench, bver=bver,
                                                       built=time.strftime("%Y-%m-%d")))
        tmp_out = out.with_suffix(".part")
        with tarfile.open(tmp_out, "w:gz") as t:
            t.add(root, arcname=top)
        tmp_out.rename(out)
    return out
